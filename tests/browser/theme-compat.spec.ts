import {test,expect,waitForReady} from "./support";

const radii=async(root:any)=>Promise.all(["sm","md","lg","xl"].map(size=>root.getByTestId(`fixture-${size}`).evaluate((el:Element)=>getComputedStyle(el).borderRadius)));
const shadow=async(node:any)=>node.evaluate((el:Element)=>getComputedStyle(el).boxShadow);

test("one Tailwind product retains legacy geometry and elevation beside v4",async({page})=> {
  await waitForReady(page);
  await page.evaluate(()=>window.__component_catalog.mount_theme_fixtures());
  const old=page.getByTestId("catalog-theme-legacy"),modern=page.getByTestId("catalog-theme-v4");
  await expect.poll(()=>radii(old)).toEqual(["4px","6px","8px","12px"]);
  expect(await radii(modern)).toEqual(["2px","4px","6px","10px"]);
  const oldShadow=await shadow(old.getByTestId("fixture-lg"));
  expect(oldShadow).toContain("0px 10px 15px -3px");
  expect(oldShadow).toContain("0px 4px 6px -4px");
  await old.getByTestId("fixture-dialog-open").click();
  const oldDialog=old.getByTestId("fixture-dialog").locator('[data-name="Dialog"]');
  expect(await shadow(oldDialog)).toBe(oldShadow);
  await modern.getByTestId("fixture-dialog-open").click();
  const newDialog=modern.getByTestId("fixture-dialog").locator('[data-name="Dialog"]');
  await modern.getByTestId("fixture-change").click();
  await expect.poll(()=>radii(modern)).toEqual(["6px","8px","10px","14px"]);
  expect(await radii(old)).toEqual(["4px","6px","8px","12px"]);
  expect(await shadow(oldDialog)).toBe(oldShadow);
  await modern.getByTestId("fixture-patch").click();
  await expect.poll(()=>radii(modern)).toEqual(["0px","0px","0px","4px"]);
  await expect.poll(()=>shadow(newDialog)).toContain("0.3");
  await modern.getByTestId("fixture-unpatch").click();
  await expect.poll(()=>radii(modern)).toEqual(["6px","8px","10px","14px"]);
  await expect.poll(()=>shadow(newDialog)).not.toContain("0.3");
  expect(await page.locator('link[href$="tailwind.css"]').count()).toBe(1);
  expect(await page.locator('link[href$="rustify.css"]').count()).toBe(0);
  await page.evaluate(()=>window.__component_catalog.dispose_theme_fixtures());
  expect(await modern.getAttribute("data-theme")).toBeNull();
});

test("two source-backed scopes isolate appearance, palettes, geometry and local layers", async ({page}, info) => {
  await waitForReady(page);
  const failures:string[]=[];
  page.on("pageerror", error=>failures.push(error.message));
  page.on("requestfailed", request=>failures.push(request.url()));
  const host=page.getByTestId("host-button");
  const hostBefore=await host.evaluate(el=>{const s=getComputedStyle(el);return [s.color,s.backgroundColor,s.fontSize,s.borderRadius];});
  await page.evaluate(()=>{
    const root=document.querySelector('#catalog-theme-legacy') as HTMLElement;
    root.style.setProperty('--primary','rgb(1 2 3)','important');
    root.setAttribute('data-theme','original');
    (window as any).__themeBoundaryCsp=[];
    document.addEventListener('securitypolicyviolation',event=>(window as any).__themeBoundaryCsp.push(event.violatedDirective));
    window.__component_catalog.mount_theme_configuration_fixtures();
  });
  const first=page.getByTestId("catalog-theme-legacy"),second=page.getByTestId("catalog-theme-v4");
  const root=first.getByTestId("config-root"),child=first.getByTestId("config-child"),grand=first.getByTestId("config-grandchild");
  const boundary=first.getByTestId("config-boundary");
  await expect(first).toHaveAttribute('data-theme','dark');
  await expect(second).toHaveAttribute('data-theme','light');
  await expect(root).toHaveCSS('border-top-width','4px');
  await expect(second.getByTestId('config-root')).toHaveCSS('border-top-width','1px');
  await expect(boundary).not.toHaveAttribute('data-theme');
  const untouched=await second.evaluate(el=>{const s=getComputedStyle(el);return [s.getPropertyValue('--primary'),s.getPropertyValue('--rustify-unit'),el.getAttribute('data-theme')];});
  await first.getByTestId('config-light').click();
  await expect(child).toHaveAttribute('data-mode','light');
  await expect(child).toHaveAttribute('data-gray','slate');
  await expect(child).toHaveAttribute('data-brand','red');
  await expect(child).toHaveAttribute('data-scaling','95');
  await expect(child).toHaveCSS('border-top-width','1px');
  await expect(grand).toHaveAttribute('data-mode','dark');
  await expect(grand).toHaveAttribute('data-gray','mauve');
  await expect(grand).toHaveCSS('border-top-width','4px');
  const unit=await child.evaluate(el=>getComputedStyle(el).getPropertyValue('--rustify-unit'));
  const color=await child.evaluate(el=>getComputedStyle(el).backgroundColor);
  await first.getByTestId('config-child-open').click();
  const layer=first.getByTestId('config-child-layer');
  await expect(layer).toHaveCSS('background-color',color);
  await expect(layer).toHaveCSS('border-top-width','1px');
  const screenshot='docs/validation/dom-components-p1/source-boundaries.png';
  await first.screenshot({path:screenshot});
  await info.attach('source boundaries',{path:screenshot,contentType:'image/png'});
  await first.getByTestId('config-parent').click();
  await expect(root).toHaveAttribute('data-scaling','110');
  await expect(child).toHaveAttribute('data-gray','sand');
  expect(await child.evaluate(el=>getComputedStyle(el).getPropertyValue('--rustify-unit'))).toBe(unit);
  expect(await layer.evaluate(el=>getComputedStyle(el).getPropertyValue('--rustify-unit'))).toBe(unit);
  await first.getByTestId('config-auto').click();
  await expect(child).toHaveAttribute('data-gray','mauve');
  await first.getByTestId('config-clear').click();
  await expect(child).toHaveAttribute('data-mode','dark');
  await expect(child).toHaveAttribute('data-scaling','110');
  await expect(boundary).not.toHaveAttribute('data-theme');
  await expect(boundary).not.toHaveAttribute('data-rustify-theme-runtime');
  expect(await boundary.evaluate(el=>(el as HTMLElement).style.length)).toBe(0);
  await expect(layer).toHaveCSS('border-top-width','4px');
  expect(await second.evaluate(el=>{const s=getComputedStyle(el);return [s.getPropertyValue('--primary'),s.getPropertyValue('--rustify-unit'),el.getAttribute('data-theme')];})).toEqual(untouched);
  await first.getByTestId('config-remove').click();
  await expect(layer).toHaveCount(0);
  await expect(boundary).toHaveCount(0);
  await page.evaluate(()=>window.__component_catalog.dispose_theme_fixtures());
  await expect(first).toHaveAttribute('data-theme','original');
  expect(await first.evaluate(el=>[(el as HTMLElement).style.getPropertyValue('--primary'),(el as HTMLElement).style.getPropertyPriority('--primary')])).toEqual(['rgb(1 2 3)','important']);
  await expect(first).not.toHaveAttribute('data-rustify-theme-owner');
  expect(await second.evaluate(el=>(el as HTMLElement).style.length)).toBe(0);
  expect(await host.evaluate(el=>{const s=getComputedStyle(el);return [s.color,s.backgroundColor,s.fontSize,s.borderRadius];})).toEqual(hostBefore);
  expect(await page.evaluate(()=>(window as any).__themeBoundaryCsp)).toEqual([]);
  expect(failures).toEqual([]);
  await first.evaluate(el=>{(el as HTMLElement).style.removeProperty('--primary');el.removeAttribute('data-theme');});
});

test("an invalid local candidate restores the outer snapshot and can be cleared", async ({page})=>{
  await waitForReady(page);
  await page.evaluate(()=>window.__component_catalog.mount_theme_configuration_fixtures());
  const first=page.getByTestId('catalog-theme-legacy'),child=first.getByTestId('config-child'),boundary=first.getByTestId('config-boundary');
  await first.getByTestId('config-light').click();
  await expect(child).toHaveAttribute('data-mode','light');
  await first.getByTestId('config-invalid').click();
  await expect(child).toHaveAttribute('data-mode','dark');
  await expect(boundary).not.toHaveAttribute('data-theme');
  expect(await boundary.evaluate(el=>(el as HTMLElement).style.length)).toBe(0);
  const diagnostics=await page.evaluate(()=>window.__component_catalog.diagnostics());
  expect(diagnostics.entries.some((entry:any)=>entry.detail.includes('invalid theme patch'))).toBe(true);
  await first.getByTestId('config-clear').click();
  await first.getByTestId('config-light').click();
  await expect(child).toHaveAttribute('data-mode','light');
});
