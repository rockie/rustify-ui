import {test, expect, waitForReady} from "./support";
import type {Page} from "@playwright/test";

test.use({fresh:true});
const state = (page:Page) => page.evaluate(() => window.__theme_studio.snapshot());
async function choose(page:Page, field:string, name:string) {
  await page.getByTestId(`studio-config-${field}`).click();
  await page.getByRole("option", {name, exact:true}).click();
}
async function color(page:Page, token:string, value:string) {
  await page.getByTestId("editor-colors").click();
  await page.getByTestId("color-search").fill("");
  await page.getByTestId(`color-token-${token}`).click();
  await page.getByTestId("color-value").fill(value);
  await page.getByTestId("color-value").press("Enter");
}
async function settled(page:Page) {
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))));
}

test("all six base choices are controlled, and preview mode stays independent of author appearance", async ({page}) => {
  await waitForReady(page);
  await expect(page.getByTestId("preset-count")).toHaveText("44");
  const before = await state(page);
  for (const [field, name, value] of [
    ["appearance", "Dark", "dark"], ["accent_color", "Violet", "violet"],
    ["gray_color", "Auto", "auto"], ["panel_background", "Translucent", "translucent"],
    ["radius", "Large", "large"], ["scaling", "110%", 110],
  ] as const) {
    await choose(page, field, name);
    await expect.poll(async () => (await state(page)).document.config[field]).toBe(value);
  }
  const configured = await state(page);
  expect(configured.document.overrides).toEqual(before.document.overrides);
  expect(configured.mode).toBe("light");
  await expect(page.getByTestId("studio-preview")).toHaveAttribute("data-theme", "light");
  await page.getByTestId("mode-dark").click();
  expect((await state(page)).document).toEqual(configured.document);
  expect((await state(page)).history).toEqual(configured.history);
  await expect(page.getByTestId("studio-preview")).toHaveAttribute("data-theme", "dark");
  await choose(page, "appearance", "Inherit");
  expect((await state(page)).mode).toBe("dark");
  await page.getByTestId("locale-zh").click();
  await expect(page.getByTestId("studio-config")).toContainText("主题基础配置");
  await expect(page.getByTestId("studio-config-accent_color-reset")).toContainText("两模式");
  await expect(page.getByTestId("token-source")).toContainText("精调来源");
  await expect(page.getByTestId("storage-operations")).toContainText("待处理");
});

test("brand reset releases exactly its responsibility keys in both modes and undo restores the whole candidate", async ({page}) => {
  await waitForReady(page);
  await color(page, "accent", "#667788");
  await color(page, "destructive", "#990011");
  await color(page, "primary", "#123456");
  await page.getByTestId("mode-dark").click();
  await color(page, "primary", "#789abc");
  await choose(page, "accent_color", "Tomato");
  const before = await state(page);
  expect(before.values.light.primary).toBe("#123456");
  expect(before.values.dark.primary).toBe("#789abc");
  const counter = page.locator('[data-theme-config="accent_color"] [data-name="ThemeOverrideCount"]');
  await expect(counter).toContainText("Light");
  await expect(counter).toContainText("Dark");
  await page.getByTestId("studio-config-accent_color-reset").click();
  const released = await state(page);
  const group = ["primary", "primary-foreground", "ring", "sidebar-primary", "sidebar-primary-foreground", "sidebar-ring"];
  for (const mode of ["light", "dark"]) {
    for (const token of group) expect(released.document.overrides[mode][token]).toBeUndefined();
    const retained = structuredClone(before.document.overrides[mode]);
    for (const token of group) delete retained[token];
    expect(released.document.overrides[mode]).toEqual(retained);
  }
  expect(released.values.light.accent).toBe("#667788");
  expect(released.values.light.destructive).toBe("#990011");
  expect(released.values.light.primary).not.toBe("#123456");
  expect(released.history.undo).toBe(before.history.undo + 1);
  await page.getByTestId("theme-undo").click();
  expect((await state(page)).document).toEqual(before.document);
  await page.getByTestId("theme-redo").click();
  expect((await state(page)).document).toEqual(released.document);
});

test("source removal and explicit same-value pin are meaningful, while untouched drafts and zero HSL are no-ops", async ({page}) => {
  await waitForReady(page);
  await choose(page, "accent_color", "Indigo");
  await page.getByTestId("studio-config-accent_color-reset").click();
  await page.getByTestId("color-token-primary").click();
  await expect(page.getByTestId("source-kind")).toHaveText("Generated by base configuration");
  const generated = await state(page);
  await page.getByTestId("color-value").focus();
  await page.getByTestId("color-search").focus();
  await settled(page);
  expect((await state(page)).document).toEqual(generated.document);
  expect((await state(page)).history).toEqual(generated.history);
  await color(page, "primary", generated.values.light.primary);
  const pinned = await state(page);
  expect(pinned.values).toEqual(generated.values);
  expect(pinned.document.overrides.light.primary).toBe(generated.values.light.primary);
  expect(pinned.history.undo).toBe(generated.history.undo + 1);
  await expect(page.getByTestId("source-kind")).toHaveText("Explicit document override");
  await page.getByTestId("source-clear").click();
  expect((await state(page)).document).toEqual(generated.document);
  await page.getByTestId("editor-controls").click();
  const before = await state(page);
  await page.getByTestId("edit-radius").focus();
  await page.getByTestId("hsl-hue").focus();
  await page.getByTestId("hsl-hue").fill("0");
  await expect(page.getByTestId("hsl-apply")).toBeDisabled();
  await page.getByTestId("hsl-hue").press("Enter");
  await page.getByTestId("edit-radius").focus();
  expect((await state(page)).document).toEqual(before.document);
  expect((await state(page)).history).toEqual(before.history);
  expect((await state(page)).resolve_count).toBe(before.resolve_count);
});

test("single-token release keeps the other mode, and common-token release clears both modes", async ({page}) => {
  await waitForReady(page);
  await color(page, "primary", "#123456");
  const dark = (await state(page)).document.overrides.dark.primary;
  await page.getByTestId("source-clear").click();
  const released = await state(page);
  expect(released.document.overrides.light.primary).toBeUndefined();
  expect(released.document.overrides.dark.primary).toBe(dark);
  await page.getByTestId("editor-controls").click();
  await page.getByTestId("edit-radius").fill("12px");
  await page.getByTestId("edit-radius").press("Enter");
  const controls = page.locator("#studio-editor-panel-controls");
  await expect(controls.getByTestId("source-token")).toHaveText("radius");
  await expect(controls.getByTestId("source-clear")).toContainText("both modes");
  await controls.getByTestId("source-clear").click();
  const common = await state(page);
  expect(common.document.overrides.light.radius).toBeUndefined();
  expect(common.document.overrides.dark.radius).toBeUndefined();
});

test("base configuration follows a committed color gesture as a separate history command", async ({page}) => {
  await waitForReady(page);
  const before = await state(page), plane = page.getByTestId("color-plane");
  await plane.scrollIntoViewIfNeeded();
  const box = (await plane.boundingBox())!;
  await page.mouse.move(box.x + box.width * .3, box.y + box.height * .4);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * .6, box.y + box.height * .5);
  await expect.poll(async () => (await state(page)).history.gesture).toBe(true);
  await page.mouse.up();
  const committed = await state(page);
  expect(committed.history.gesture).toBe(false);
  expect(committed.history.undo).toBe(before.history.undo + 1);
  await choose(page, "scaling", "110%");
  const configured = await state(page);
  expect(configured.document.config.scaling).toBe(110);
  expect(configured.document.overrides).toEqual(committed.document.overrides);
  expect(configured.history.undo).toBe(committed.history.undo + 1);
  await choose(page, "scaling", "110%");
  expect((await state(page)).history).toEqual(configured.history);
  await page.getByTestId("theme-undo").click();
  expect((await state(page)).document).toEqual(committed.document);
});

test("native text undo changes only the uncommitted draft and does not consume theme history", async ({page}) => {
  await waitForReady(page);
  const before = await state(page), input = page.getByTestId("color-value");
  await input.focus(); await input.press("ControlOrMeta+a");
  await input.pressSequentially("#123456");
  expect(await input.inputValue()).toBe("#123456");
  expect((await state(page)).document).toEqual(before.document);
  await input.press("ControlOrMeta+z");
  expect(await input.inputValue()).not.toBe("#123456");
  expect((await state(page)).document).toEqual(before.document);
  expect((await state(page)).history).toEqual(before.history);
  await input.press("Escape");
  expect((await state(page)).document).toEqual(before.document);
  expect((await state(page)).resolve_count).toBe(before.resolve_count);
});
