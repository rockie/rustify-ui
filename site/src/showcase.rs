//! The official site's own showcase directory: which released family lives at
//! which shareable place, which registered demo renders it, and which public
//! API path and guide page describe it. Static facts only; no runtime routing
//! and no SDK registry lookups. Serves the home page, the category pages and
//! the individual sample pages that link back here.

pub struct ShowcaseEntry {
    /// Category slug; also the `/components/<group>/` route segment.
    pub group: &'static str,
    /// The page a reader can share for this family.
    pub route: &'static str,
    /// The anchor on that page (`#<anchor>`), empty when the page itself is it.
    pub anchor: &'static str,
    pub title: &'static str,
    /// Registered demo name in `site/src/lib.rs`, empty when the page renders
    /// the sample through its own registered detail-page demo.
    pub demo: &'static str,
    /// Public `rustify_components` / `rustify_dom` API paths shown with it.
    pub public_paths: &'static [&'static str],
    /// Site guide route for this family, empty when there is none.
    pub guide: &'static str,
}

