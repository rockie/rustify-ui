//! The frozen migration fact source: every baseline (11b69129) public key
//! and where it stands in the current API. A name ending in `.*` or `::*` is
//! a wildcard; an exact key wins over any wildcard. Kept rows may leave
//! `guide` empty.

/// What happened to a baseline key.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LegacyFate {
    Kept,
    Changed,
    Replaced,
    Removed,
}

impl LegacyFate {
    pub fn name(self) -> &'static str {
        match self {
            Self::Kept => "kept",
            Self::Changed => "changed",
            Self::Replaced => "replaced",
            Self::Removed => "removed",
        }
    }
}

/// One baseline key group and its current destination.
pub struct LegacyEntry {
    /// Baseline keys; a trailing `.*` or `::*` is a wildcard and exact keys
    /// win over it.
    pub names: &'static [&'static str],
    pub fate: LegacyFate,
    pub destination: &'static str,
    pub reason: &'static str,
    /// Migration-guide anchor or a real example path; may be empty for Kept.
    pub guide: &'static str,
}

impl LegacyEntry {
    /// Whether one of this entry's names resolves `key`.
    pub fn resolves(&self, key: &str) -> bool {
        self.names.iter().any(|name| {
            if let Some(prefix) = name.strip_suffix('*') {
                key.starts_with(prefix)
            } else {
                *name == key
            }
        })
    }
}

