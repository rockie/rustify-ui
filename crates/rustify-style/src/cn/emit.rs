use serde::Serialize;

use super::{
    compiler::{compile_utf16_model, Utf16CompiledModel},
    CnError, Config, Utf16Config,
};

/// Language of the emitted table-data module; it does not contain a compiler.
#[derive(Clone, Copy, Default)]
pub enum EmitLanguage {
    #[default]
    Javascript,
    Typescript,
}

/// Upstream table-module emission options.
#[derive(Default)]
pub struct EmitOptions<'a> {
    pub language: EmitLanguage,
    pub banner: Option<&'a str>,
}

fn json(value: &impl Serialize) -> Result<String, CnError> {
    serde_json::to_string(value).map_err(|error| CnError::new(error.to_string()))
}

fn pack(values: &[i32]) -> Result<String, CnError> {
    let mut output = String::new();
    for value in values {
        if *value < 0 || *value + 48 >= 0xd800 {
            return Err(CnError::new(format!(
                "cn compiler: unpackable value {value}"
            )));
        }
        if let Some(c) = char::from_u32((*value + 48) as u32) {
            output.push(c);
        }
    }
    json(&output)
}

fn deltas(values: &[i32]) -> Vec<i32> {
    let mut previous = 0;
    values
        .iter()
        .map(|value| {
            let delta = *value - previous;
            previous = *value;
            delta
        })
        .collect()
}

fn zig(values: &[i32]) -> Vec<i32> {
    values
        .iter()
        .map(|value| (*value << 1) ^ (*value >> 31))
        .collect()
}
fn counts(starts: &[i32]) -> Vec<i32> {
    starts.windows(2).map(|pair| pair[1] - pair[0]).collect()
}

fn json_utf16(units: &[u16]) -> Result<String, CnError> {
    let mut output = String::from("\"");
    for decoded in char::decode_utf16(units.iter().copied()) {
        match decoded {
            Ok(c) => {
                let escaped = json(&c.to_string())?;
                output.push_str(&escaped[1..escaped.len() - 1]);
            }
            Err(error) => output.push_str(&format!("\\u{:04x}", error.unpaired_surrogate())),
        }
    }
    output.push('"');
    Ok(output)
}

/// Emit byte-identical upstream JS/TS table source from the Rust compiler.
pub fn compile_to_source(config: &Config, options: EmitOptions<'_>) -> Result<String, CnError> {
    let model = compile_utf16_model(&Utf16Config::from(config.clone()), None, None)?;
    compile_utf16_model_to_source(&model, options)
}

/// Emit a compiled UTF-16 model without a native String configuration adapter.
pub fn compile_utf16_model_to_source(
    model: &Utf16CompiledModel,
    options: EmitOptions<'_>,
) -> Result<String, CnError> {
    let table = &model.compiled.tables;
    if !table.custom_validator_names.is_empty() {
        return Err(CnError::new(format!(
            "cn compiler: configs with custom validator functions cannot be emitted as a module (functions are not serializable): {}. Use createCn(config) at runtime instead.",
            table.custom_validator_names.iter().map(|s| String::from_utf16_lossy(s)).collect::<Vec<_>>().join(", ")
        )));
    }
    let ts = matches!(options.language, EmitLanguage::Typescript);
    let sets: Vec<Vec<u16>> = model
        .sets
        .iter()
        .map(|tails| {
            let first = &tails[0];
            let last = &tails[tails.len() - 1];
            let common_units = first
                .iter()
                .zip(last.iter())
                .take_while(|(left, right)| left == right)
                .count();
            let mut units: Vec<u16> = first.iter().copied().take(common_units).collect();
            for tail in tails {
                units.push(32);
                units.extend(tail.iter().copied().skip(common_units));
            }
            units
        })
        .collect();
    let mut sets_text = Vec::new();
    for (index, set) in sets.into_iter().enumerate() {
        if index > 0 {
            sets_text.push(124);
        }
        sets_text.extend(set);
    }
    let mut anchors = Vec::new();
    let mut vlists = Vec::new();
    for (anchor, value) in table.node_vlist.iter().enumerate() {
        if *value >= 0 {
            anchors.push(anchor as i32);
            vlists.push(*value);
        }
    }
    let att_anchors: Vec<_> = model
        .attachments
        .iter()
        .map(|(anchor, _, _)| *anchor as i32)
        .collect();
    let att_groups: Vec<_> = model
        .attachments
        .iter()
        .map(|(_, gid, _)| *gid as i32)
        .collect();
    let att_sets: Vec<_> = model
        .attachments
        .iter()
        .map(|(_, _, set)| *set as i32)
        .collect();
    let values = vec![
        options
            .banner
            .unwrap_or("// GENERATED by the cn compiler. Do not edit.")
            .to_owned(),
        "48".to_owned(),
        if ts {
            "(s: string, o = 0): Int32Array"
        } else {
            "(s, o = 0)"
        }
        .to_owned(),
        if ts {
            "(counts: Int32Array): Int32Array"
        } else {
            "(counts)"
        }
        .to_owned(),
        if ts { "!" } else { "" }.to_owned(),
        if ts { "(s: string): Int32Array" } else { "(s)" }.to_owned(),
        table.group_count.to_string(),
        if ts { ": string[]" } else { "" }.to_owned(),
        format!(
            "[{}]",
            table
                .custom_validator_names
                .iter()
                .map(|s| json_utf16(s))
                .collect::<Result<Vec<_>, _>>()?
                .join(",")
        ),
        pack(&counts(&table.edge_start))?,
        pack(&counts(&table.label_start))?,
        json_utf16(&table.label_text)?,
        pack(
            &table
                .node_group
                .iter()
                .map(|gid| gid + 1)
                .collect::<Vec<_>>(),
        )?,
        pack(&counts(&table.vlist_pat))?,
        pack(&table.vlist_ops)?,
        pack(&table.vlist_ref)?,
        pack(&zig(&deltas(&table.vlist_group)))?,
        table.node_group.len().to_string(),
        pack(&zig(&deltas(&anchors)))?,
        pack(&zig(&deltas(&vlists)))?,
        json_utf16(&sets_text)?,
        pack(&zig(&deltas(&att_anchors)))?,
        pack(&zig(&deltas(&att_groups)))?,
        pack(&zig(&deltas(&att_sets)))?,
        table.lit_anchor.len().to_string(),
        table.pool_offsets.len().to_string(),
        pack(&zig(&deltas(&table.adj_gid)))?,
        pack(&counts(&table.adj_start))?,
        pack(&zig(&deltas(&table.adj_tgt)))?,
        pack(&table.pat_gid)?,
        pack(&table.pat_tgt)?,
        pack(&table.postfix_lookup_groups)?,
        json_utf16(&table.order_sensitive_modifiers)?,
        if let Some(prefix) = model
            .compiled
            .prefix
            .as_deref()
            .filter(|prefix| !prefix.is_empty())
        {
            format!(" prefix: {},", json_utf16(prefix)?)
        } else {
            String::new()
        },
    ];
    let template = include_str!("../../upstream/cn/emit-template.txt");
    let mut output = String::new();
    for (index, part) in template.split("@@").enumerate() {
        if index % 2 == 0 {
            output.push_str(part);
        } else {
            let key: usize = part
                .parse()
                .map_err(|_| CnError::new("cn: invalid emission template"))?;
            output.push_str(
                values
                    .get(key)
                    .ok_or_else(|| CnError::new("cn: invalid emission template"))?,
            );
        }
    }
    Ok(output)
}
