//! Project-fitted table builds, source discovery, and incremental host adapters.

use std::collections::HashSet;

use super::{compiler, CnError, Config, EmitLanguage, EmitOptions};

/// Pure table-build options after the caller resolves sources and configuration.
pub struct BuildOptions<'a> {
    pub out: &'a str,
    pub full: bool,
    pub previous_source: Option<&'a str>,
}

impl Default for BuildOptions<'_> {
    fn default() -> Self {
        Self {
            out: "cn-tables.mjs",
            full: false,
            previous_source: None,
        }
    }
}

/// A table build artifact before a host adapter writes the output file.
pub struct BuildReport {
    pub source: String,
    pub changed: bool,
    pub tokens: Vec<String>,
    pub config: Config,
    pub full_config: Config,
    pub used_groups: Option<usize>,
    pub total_groups: Option<usize>,
}

/// Apply the original cn token extractor, including its UTF-16 length cap.
pub fn extract_tokens(content: &str, into: &mut Vec<String>) -> usize {
    let mut skipped = 0;
    let mut seen: HashSet<String> = into.iter().cloned().collect();
    for candidate in content.split(|c: char| {
        matches!(c, '<' | '>' | '"' | '\'' | '`') || super::validators::is_whitespace(c)
    }) {
        let candidate = candidate.trim_end_matches(':');
        if candidate.is_empty() {
            continue;
        }
        if candidate.encode_utf16().count() > 8192 {
            skipped += 1;
            continue;
        }
        if seen.insert(candidate.to_owned()) {
            into.push(candidate.to_owned());
        }
    }
    skipped
}

/// Extract code-unit candidates, invoking the callback even for duplicates.
/// This preserves Set subclass/add side effects at the ECMAScript boundary.
pub fn extract_tokens_utf16(
    content: &[u16],
    mut add: impl FnMut(&[u16]) -> Result<(), CnError>,
) -> Result<usize, CnError> {
    let mut skipped = 0;
    for candidate in content.split(|c| {
        matches!(*c, 60 | 62 | 34 | 39 | 96)
            || char::from_u32(*c as u32).is_some_and(super::validators::is_whitespace)
    }) {
        let end = candidate
            .iter()
            .rposition(|c| *c != 58)
            .map_or(0, |i| i + 1);
        let candidate = &candidate[..end];
        if candidate.is_empty() {
            continue;
        }
        if candidate.len() > 8192 {
            skipped += 1;
            continue;
        }
        add(candidate)?;
    }
    Ok(skipped)
}

/// Build full or project-fitted tables from already resolved complete tokens.
pub fn build_tokens(
    config: &Config,
    inputs: &[&str],
    options: BuildOptions<'_>,
) -> Result<BuildReport, CnError> {
    let mut seen = HashSet::new();
    let tokens: Vec<String> = if options.full {
        Vec::new()
    } else {
        inputs
            .iter()
            .filter(|token| !token.is_empty() && seen.insert(**token))
            .map(|token| (*token).to_owned())
            .collect()
    };
    let (fitted, used_groups, total_groups) = if options.full {
        (config.clone(), None, None)
    } else {
        let subset = compiler::subset_config(config, tokens.iter().map(String::as_str))?;
        (
            subset.config,
            Some(subset.used_groups),
            Some(subset.total_groups),
        )
    };
    let filename = std::path::Path::new(options.out)
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("");
    let banner = format!(
        "// GENERATED by `cn build` — do not edit.\n// Pair with createCn from \"cn/engine\":\n//   import tables from \"./{filename}\"\n//   import {{ createCn }} from \"cn/engine\"\n//   export const cn = createCn(tables)"
    );
    let source = compiler::compile_to_source(
        &fitted,
        EmitOptions {
            language: if options.out.ends_with(".ts") {
                EmitLanguage::Typescript
            } else {
                EmitLanguage::Javascript
            },
            banner: Some(&banner),
        },
    )?;
    let changed = options
        .previous_source
        .is_none_or(|previous| previous != source);
    Ok(BuildReport {
        source,
        changed,
        tokens,
        config: fitted,
        full_config: config.clone(),
        used_groups,
        total_groups,
    })
}

