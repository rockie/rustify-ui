//! Deterministic generation from the vendored, constant-only Colors snapshot.

use std::collections::BTreeMap;
use std::io::Write;
use std::path::Path;
use std::process::{Command, Stdio};

const FAMILIES: &[&str] = &[
    "gray", "mauve", "slate", "sage", "olive", "sand", "tomato", "red", "ruby", "crimson", "pink",
    "plum", "purple", "violet", "iris", "indigo", "blue", "cyan", "teal", "jade", "green", "grass",
    "brown", "bronze", "gold", "sky", "mint", "lime", "yellow", "amber", "orange",
];
const HEADER: &str = "// Generated by `mbx xtask colors` from vendor/colors; do not edit.\n";
const CSS_HEADER: &str =
    "/* Generated by mbx xtask colors; MIT notice: ../vendor/colors/LICENSE */\n";
type Scales = BTreeMap<String, Vec<(String, String)>>;

/// Accept only `export const name = { key: "value", ... };`, not executable TS.
fn parse(text: &str) -> Result<Scales, String> {
    let mut scales = BTreeMap::new();
    let mut current: Option<(String, Vec<(String, String)>)> = None;
    for (i, line) in text.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() {
            continue;
        }
        let error = || {
            format!(
                "line {}: expected a constant color object, found {line:?}",
                i + 1
            )
        };
        if let Some((_, values)) = &mut current {
            if line == "};" {
                let (name, values) = current.take().ok_or_else(error)?;
                if scales.insert(name.clone(), values).is_some() {
                    return Err(format!("duplicate scale {name}"));
                }
                continue;
            }
            let (key, value) = line.split_once(": \"").ok_or_else(error)?;
            let value = value.strip_suffix("\",").ok_or_else(error)?;
            if !identifier(key) || !color_literal(value) {
                return Err(error());
            }
            values.push((key.to_string(), value.to_string()));
        } else {
            let name = line
                .strip_prefix("export const ")
                .and_then(|line| line.strip_suffix(" = {"))
                .filter(|name| identifier(name))
                .ok_or_else(error)?;
            current = Some((name.to_string(), Vec::new()));
        }
    }
    if current.is_some() {
        return Err("unterminated scale".to_string());
    }
    Ok(scales)
}

fn identifier(text: &str) -> bool {
    !text.is_empty() && text.bytes().all(|b| b.is_ascii_alphanumeric())
}

fn color_literal(value: &str) -> bool {
    if let Some(hex) = value.strip_prefix('#') {
        return matches!(hex.len(), 6 | 8) && hex.bytes().all(|b| b.is_ascii_hexdigit());
    }
    value
        .strip_prefix("rgba(")
        .or_else(|| value.strip_prefix("color(display-p3 "))
        .and_then(|v| v.strip_suffix(')'))
        .is_some_and(|v| {
            !v.is_empty()
                && v.bytes()
                    .all(|b| b.is_ascii_digit() || matches!(b, b' ' | b',' | b'.' | b'/'))
        })
}

fn variant(name: &str) -> String {
    format!("{}{}", name[..1].to_ascii_uppercase(), &name[1..])
}

fn checked_values<'a>(scales: &'a Scales, name: &str, key: &str) -> Result<Vec<&'a str>, String> {
    let values = scales.get(name).ok_or_else(|| format!("missing {name}"))?;
    if values.len() != 12 {
        return Err(format!(
            "{name}: expected twelve steps, got {}",
            values.len()
        ));
    }
    for (i, (actual, _)) in values.iter().enumerate() {
        let expected = format!("{key}{}", i + 1);
        if actual != &expected {
            return Err(format!(
                "{name}: expected ordered key {expected}, got {actual}"
            ));
        }
    }
    Ok(values.iter().map(|(_, v)| v.as_str()).collect())
}

fn stylesheet(
    family: &str,
    mode: Option<&str>,
    alpha: bool,
    p3: bool,
    values: &[&str],
) -> (String, String) {
    let stem = match mode {
        Some(mode) => format!("{family}-{mode}{}", if alpha { "-alpha" } else { "" }),
        None => format!("{family}-alpha"),
    };
    let mut css = CSS_HEADER.to_string();
    if p3 {
        css.push_str(&format!("@import \"./{stem}.css\";\n\n@supports (color: color(display-p3 1 1 1)) {{\n  @media (color-gamut: p3) {{\n"));
    }
    let indent = if p3 { "    " } else { "" };
    let selector = format!("[data-rustify-colors~=\"{family}\"]");
    let selector = match mode {
        Some(mode) => format!("{selector}[data-rustify-colors-mode=\"{mode}\"]"),
        None => selector,
    };
    css.push_str(&format!("{indent}{selector} {{\n"));
    for (i, value) in values.iter().enumerate() {
        let a = if alpha { "a" } else { "" };
        css.push_str(&format!("{indent}  --{family}-{a}{}: {value};\n", i + 1));
    }
    css.push_str(&format!("{indent}}}\n"));
    if p3 {
        css.push_str("  }\n}\n");
    }
    (
        format!("css/{stem}{}.css", if p3 { "-p3" } else { "" }),
        css,
    )
}

fn rustfmt(source: &str) -> Result<String, String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt stdin unavailable")?
        .write_all(source.as_bytes())
        .map_err(|e| e.to_string())?;
    let output = child.wait_with_output().map_err(|e| e.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).map_err(|e| e.to_string())
}

fn generate(root: &Path) -> Result<BTreeMap<String, String>, String> {
    let mut inputs = BTreeMap::new();
    for file in ["light", "dark", "blackA", "whiteA"] {
        let path = root.join(format!("vendor/colors/src/{file}.ts"));
        let text =
            std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let scales = parse(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let expected = if matches!(file, "light" | "dark") {
            31 * 4
        } else {
            2
        };
        if scales.len() != expected {
            return Err(format!(
                "{file}: expected {expected} scales, got {}",
                scales.len()
            ));
        }
        inputs.insert(file, scales);
    }
    let mut outputs = BTreeMap::new();
    let mut families = format!("{HEADER}/// The thirty-one named color families in the pinned snapshot.\n#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]\npub enum ColorFamily {{\n");
    for family in FAMILIES {
        families.push_str(&format!("/// The {family} family.\n{},\n", variant(family)));
    }
    families.push_str("}\nimpl ColorFamily {\n/// All available families in palette order.\npub const ALL: &'static [Self] = &[\n");
    for family in FAMILIES {
        families.push_str(&format!("Self::{},\n", variant(family)));
    }
    families.push_str("];\n/// The lowercase asset and CSS name.\npub const fn name(self) -> &'static str { match self {\n");
    for family in FAMILIES {
        families.push_str(&format!("Self::{} => \"{family}\",\n", variant(family)));
    }
    families.push_str("}}\n/// Looks up an exact lowercase family name.\npub fn from_name(name: &str) -> Option<Self> { match name {\n");
    for family in FAMILIES {
        families.push_str(&format!(
            "\"{family}\" => Some(Self::{}),\n",
            variant(family)
        ));
    }
    families.push_str("_ => None,\n}}}\n");
    outputs.insert("src/families.rs".to_string(), rustfmt(&families)?);
    for p3 in [false, true] {
        let mut data =
            format!("{HEADER}use super::{{ColorFamily, ColorMode, ColorScale, CssAsset}};\n");
        let mut scale_arms = String::new();
        let mut css_arms = String::new();
        for family in FAMILIES {
            for mode in ["light", "dark"] {
                for alpha in [false, true] {
                    let name = format!(
                        "{family}{}{}{}",
                        if mode == "dark" { "Dark" } else { "" },
                        if p3 { "P3" } else { "" },
                        if alpha { "A" } else { "" }
                    );
                    let key = format!("{family}{}", if alpha { "A" } else { "" });
                    let values = checked_values(&inputs[mode], &name, &key)?;
                    let pattern = format!(
                        "(ColorFamily::{}, ColorMode::{}, {alpha})",
                        variant(family),
                        variant(mode)
                    );
                    scale_arms.push_str(&format!("{pattern} => ColorScale(&{values:?}),\n"));
                    let (path, css) = stylesheet(family, Some(mode), alpha, p3, &values);
                    css_arms.push_str(&format!(
                        "{pattern} => CssAsset {{path: {path:?}, content: include_str!({:?})}},\n",
                        format!("../{path}")
                    ));
                    outputs.insert(path, css);
                }
            }
        }
        for family in ["black", "white"] {
            let name = format!("{family}{}A", if p3 { "P3" } else { "" });
            let values = checked_values(
                &inputs[format!("{family}A").as_str()],
                &name,
                &format!("{family}A"),
            )?;
            let constant = family.to_ascii_uppercase();
            data.push_str(&format!(
                "pub(super) const {constant}_ALPHA: ColorScale = ColorScale(&{values:?});\n"
            ));
            let (path, css) = stylesheet(family, None, true, p3, &values);
            data.push_str(&format!("pub(super) const {constant}_ALPHA_CSS: CssAsset = CssAsset {{path: {path:?}, content: include_str!({:?})}};\n", format!("../{path}")));
            outputs.insert(path, css);
        }
        data.push_str(&format!("pub(super) fn scale(family: ColorFamily, mode: ColorMode, alpha: bool) -> ColorScale {{ match (family,mode,alpha) {{\n{scale_arms}}}}}\n"));
        data.push_str(&format!("pub(super) fn css(family: ColorFamily, mode: ColorMode, alpha: bool) -> CssAsset {{ match (family,mode,alpha) {{\n{css_arms}}}}}\n"));
        outputs.insert(
            format!("src/{}.rs", if p3 { "p3" } else { "srgb" }),
            rustfmt(&data)?,
        );
    }
    Ok(outputs)
}

fn theme_roles(root: &Path) -> Result<String, String> {
    let mut source = String::from("// Generated by `mbx xtask colors` from theme/vendor/themes; do not edit.\nuse rustify_colors::ColorFamily;\nuse super::{config::PaletteRoles, Rgba};\n");
    let semantics = std::fs::read_to_string(
        root.join("crates/rustify-dom/src/theme/vendor/themes/src/styles/tokens/color.css"),
    )
    .map_err(|e| e.to_string())?;
    let semantic = |role: &str| -> Vec<&str> {
        let prefix = format!("--color-{role}: ");
        semantics
            .lines()
            .filter_map(|line| line.trim().strip_prefix(&prefix)?.strip_suffix(';'))
            .collect()
    };
    let surfaces = semantic("surface");
    let panels = semantic("panel-translucent");
    if semantic("panel-solid") != ["white", "var(--gray-2)"]
        || panels.len() != 2
        || panels[1] != "var(--gray-a2)"
        || surfaces.len() != 2
    {
        return Err("unrecognized reference panel/surface roles".into());
    }
    let rgba = |value: &str| -> Result<(u8, f64), String> {
        let (rgb, alpha) = if let Some(value) = value.strip_prefix("rgba(255, 255, 255, ") {
            (1, value)
        } else if let Some(value) = value.strip_prefix("rgba(0, 0, 0, ") {
            (0, value)
        } else {
            return Err(format!("unsupported reference surface {value}"));
        };
        let alpha = alpha
            .strip_suffix(')')
            .and_then(|v| v.parse::<f64>().ok())
            .filter(|v| v.is_finite() && (0.0..=1.0).contains(v))
            .ok_or_else(|| format!("invalid reference surface {value}"))?;
        Ok((rgb, alpha))
    };
    source.push_str("pub(super) const SURFACES: [Rgba; 2] = [\n");
    for value in surfaces {
        let (rgb, alpha) = rgba(value)?;
        source.push_str(&format!(
            "Rgba {{r: {rgb}., g: {rgb}., b: {rgb}., a: {alpha:?}}},\n"
        ));
    }
    source.push_str("];\n");
    let (rgb, alpha) = rgba(panels[0])?;
    source.push_str(&format!("pub(super) const LIGHT_PANEL: Rgba = Rgba {{r: {rgb}., g: {rgb}., b: {rgb}., a: {alpha:?}}};\n"));
    source.push_str("pub(super) fn roles(family: ColorFamily) -> PaletteRoles { match family {\n");
    for family in FAMILIES {
        let path = root.join(format!(
            "crates/rustify-dom/src/theme/vendor/themes/src/styles/tokens/colors/{family}.css"
        ));
        let text =
            std::fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let declarations = |role: &str| -> Vec<&str> {
            let prefix = format!("--{family}-{role}: ");
            text.lines()
                .filter_map(|line| {
                    line.trim()
                        .strip_prefix(&prefix)?
                        .split_once(';')
                        .map(|(value, _)| value)
                })
                .collect()
        };
        let contrast = declarations("contrast");
        let surface: Vec<_> = declarations("surface")
            .into_iter()
            .filter(|value| value.starts_with('#'))
            .collect();
        let indicators: Vec<_> = declarations("indicator")
            .into_iter()
            .map(|value| {
                value
                    .strip_prefix(&format!("var(--{family}-"))
                    .and_then(|v| v.strip_suffix(')'))
                    .and_then(|v| v.parse::<u8>().ok())
                    .filter(|v| (1..=12).contains(v))
                    .ok_or_else(|| format!("{family}: invalid indicator {value}"))
            })
            .collect::<Result<_, _>>()?;
        let tracks = declarations("track");
        if contrast.len() != 1
            || surface.len() != 2
            || indicators.len() != 2
            || !(2..=3).contains(&tracks.len())
        {
            return Err(format!("{family}: incomplete or unrecognized theme roles"));
        }
        if contrast[0] != "white" && !color_literal(contrast[0])
            || surface.iter().any(|v| !color_literal(v))
        {
            return Err(format!("{family}: invalid contrast/surface literal"));
        }
        for i in 0..2 {
            if tracks[i] != format!("var(--{family}-{})", indicators[i]) {
                return Err(format!("{family}: unexpected base track"));
            }
        }
        let dark_track_mix = if let Some(mix) = tracks.get(2) {
            mix.strip_prefix(&format!(
                "color-mix(in oklab, var(--{family}-8), var(--{family}-9) "
            ))
            .and_then(|v| v.strip_suffix("%)"))
            .and_then(|v| v.parse::<u8>().ok())
            .filter(|v| matches!(v, 65 | 75))
            .ok_or_else(|| format!("{family}: unsupported track mix {mix}"))?
        } else {
            0
        };
        source.push_str(&format!("ColorFamily::{} => PaletteRoles {{contrast: {:?}, surface: {:?}, indicator: {:?}, dark_track_mix: {dark_track_mix}}},\n", variant(family), contrast[0], surface, indicators));
    }
    source.push_str("}}\n");
    rustfmt(&source)
}

pub fn run(args: &[String]) -> Result<(), String> {
    if args.iter().any(|arg| arg != "--check") || args.len() > 1 {
        return Err("usage: mbx xtask colors [--check]".to_string());
    }
    let check = !args.is_empty();
    let root = crate::build::repo_root();
    let outputs = generate(&root.join("crates/rustify-colors"))?;
    let mut outputs: BTreeMap<_, _> = outputs
        .into_iter()
        .map(|(path, content)| (format!("crates/rustify-colors/{path}"), content))
        .collect();
    outputs.insert(
        "crates/rustify-dom/src/theme/palette_roles.rs".to_string(),
        theme_roles(&root)?,
    );
    let mut stale = Vec::new();
    for (path, expected) in &outputs {
        let target = root.join(path);
        if std::fs::read_to_string(&target).ok().as_ref() == Some(expected) {
            continue;
        }
        if check {
            stale.push(path.as_str());
        } else {
            std::fs::create_dir_all(target.parent().ok_or("asset has no parent")?)
                .map_err(|e| e.to_string())?;
            std::fs::write(&target, expected).map_err(|e| format!("{}: {e}", target.display()))?;
        }
    }
    for entry in std::fs::read_dir(root.join("crates/rustify-colors/css"))
        .into_iter()
        .flatten()
    {
        let path = entry.map_err(|e| e.to_string())?.path();
        let relative = format!(
            "crates/rustify-colors/css/{}",
            path.file_name()
                .ok_or("asset has no name")?
                .to_string_lossy()
        );
        if !outputs.contains_key(&relative) {
            return Err(format!(
                "unexpected Colors asset {relative}; remove stale generated assets explicitly"
            ));
        }
    }
    if !stale.is_empty() {
        return Err(format!(
            "Colors outputs are stale or missing ({} files); run `mbx xtask colors`: {}",
            stale.len(),
            stale.join(", ")
        ));
    }
    println!("Colors: 31 families × 2 modes × 2 alpha variants × 2 gamuts + blackA/whiteA; {} deterministic files {}", outputs.len(), if check { "checked" } else { "generated" });
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn rejects_executable_or_unrecognized_typescript_without_evaluation() {
        for text in [
            "alert('x')",
            "export const red = makeColors();",
            "export const red = {\nred1: fn(),\n};",
            "export const red = {\nred1: \"#ffffff\",\n};\nsideEffect();",
            "export const red = {\nred1: \"url(x)\",\n};",
            "export const red = {\n",
        ] {
            assert!(parse(text).is_err(), "{text}");
        }
    }

    #[test]
    fn requires_exact_order_complete_scales_and_unique_exports() {
        let duplicate = "export const red = {\n};\nexport const red = {\n};";
        assert!(parse(duplicate).is_err());
        let values = (1..=12)
            .rev()
            .map(|i| (format!("red{i}"), "#ffffff".to_string()))
            .collect();
        assert!(
            checked_values(&BTreeMap::from([("red".to_string(), values)]), "red", "red").is_err()
        );
        assert!(checked_values(&BTreeMap::new(), "red", "red").is_err());
    }

    #[test]
    fn original_strings_are_not_normalized() {
        let scales =
            parse("export const blackA = {\nblackA1: \"rgba(0, 0, 0, 0.05)\",\n};").unwrap();
        assert_eq!(scales["blackA"][0].1, "rgba(0, 0, 0, 0.05)");
    }
}
